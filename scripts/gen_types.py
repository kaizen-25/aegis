"""Generate dashboard/src/types/contracts.ts from the Pydantic contracts.

Run from the repo root: .venv\\Scripts\\python scripts\\gen_types.py
"""
import json
import subprocess
import sys
import tempfile
from pathlib import Path

from pydantic.json_schema import models_json_schema

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from contracts import models  # noqa: E402

EXPORTED = [
    models.ActionRequest,
    models.AuditRecord,
    models.Decision,
    models.LiveEvent,
    models.PolicyFile,
    models.ReviewTicket,
    models.Scenario,
    models.SessionRecord,
    models.TaskScope,
    models.OutboxEmail,
    models.ScenarioSummary,
    models.RunStarted,
    models.EvalReport,
]
OUTPUT = ROOT / "dashboard" / "src" / "types" / "contracts.ts"
BANNER = "/* GENERATED by scripts/gen_types.py from /contracts. Do not edit by hand. */"


def main() -> None:
    _, schema = models_json_schema(
        [(model, "serialization") for model in EXPORTED],
        ref_template="#/$defs/{model}",
    )
    schema["title"] = "AegisContracts"
    schema["type"] = "object"
    schema["properties"] = {
        model.__name__: {"$ref": f"#/$defs/{model.__name__}"} for model in EXPORTED
    }
    schema["additionalProperties"] = False

    with tempfile.TemporaryDirectory() as folder:
        source = Path(folder) / "contracts.schema.json"
        source.write_text(json.dumps(schema, indent=2), encoding="utf-8")
        result = subprocess.run(
            ["npx", "--no-install", "json2ts", "-i", str(source), "--no-additionalProperties", "--bannerComment", BANNER],
            cwd=ROOT / "dashboard",
            capture_output=True,
            text=True,
            encoding="utf-8",
            shell=sys.platform == "win32",
        )
    if result.returncode != 0:
        raise SystemExit(result.stderr)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(result.stdout, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
